/**
 * Writes Forma's read-only layout script into the companion (2026-11-09, the
 * SQL Server programme, Phase 2): tools/RepxDesigner/SqlScripts.cs holds the
 * same text as SCHEMA_SCRIPT in src/lib/sqlSchemaScript.ts, so the companion
 * runs exactly the script a person runs in SSMS, and never one the browser
 * sends it. src/lib/sqlCompanion.test.ts fails when the two differ.
 *
 *   npx tsx scripts/companion-scripts.ts
 *
 * Pure ASCII, as every script here is: each character outside it is written
 * as a \uXXXX escape, which C# and JSON read alike.
 */
import { writeFileSync } from 'node:fs';
import { SCHEMA_SCRIPT } from '../src/lib/sqlSchemaScript';

const literal = (line: string) =>
  '"' +
  [...line]
    .map((c) => {
      if (c === '\\') return '\\\\';
      if (c === '"') return '\\"';
      if (c === '\t') return '\\t';
      const code = c.charCodeAt(0);
      return code < 32 || code > 126 ? `\\u${code.toString(16).padStart(4, '0')}` : c;
    })
    .join('') +
  '"';

const lines = SCHEMA_SCRIPT.split('\n');
const body = lines.map((line, i) => `            ${literal(i < lines.length - 1 ? `${line}\n` : line)}`).join(' +\n');

writeFileSync(
  'tools/RepxDesigner/SqlScripts.cs',
  `// Generated by scripts/companion-scripts.ts from SCHEMA_SCRIPT in src/lib/sqlSchemaScript.ts. Do not edit.
namespace RepxDesigner
{
    internal static class SqlScripts
    {
        /// <summary>Forma's read-only layout script, the text a person runs in SSMS.</summary>
        public const string Schema =
${body};
    }
}
`.replace(/\r\n/g, '\n'),
);
console.log(`SqlScripts.cs: ${lines.length} lines`);
