/**
 * Writes Forma's read-only SQL into the companion (2026-11-09, the SQL Server
 * programme, Phase 2): tools/RepxDesigner/SqlScripts.cs holds the same text as
 * SCHEMA_SCRIPT in src/lib/sqlSchemaScript.ts, so the companion runs exactly
 * the script a person runs in SSMS, and never one the browser sends it. Since
 * 2026-11-25 (the CLI and Forma Designer work's wave 6, D2-5) it also holds
 * SAMPLE_OBJECT_SCRIPT, what Forma Designer runs for each table or view it is
 * asked sample rows of. src/lib/sqlCompanion.test.ts fails when either differs.
 *
 *   npx tsx scripts/companion-scripts.ts
 *
 * Pure ASCII, as every script here is: each character outside it is written
 * as a \uXXXX escape, which C# and JSON read alike.
 */
import { writeFileSync } from 'node:fs';
import { SAMPLE_OBJECT_SCRIPT, SCHEMA_SCRIPT } from '../src/lib/sqlSchemaScript';

const literal = (line: string) =>
  '"' +
  [...line]
    .map((c) => {
      if (c === '\\') return '\\\\';
      if (c === '"') return '\\"';
      if (c === '\t') return '\\t';
      const code = c.charCodeAt(0);
      return code < 32 || code > 126 ? `\\u${code.toString(16).padStart(4, '0')}` : c;
    })
    .join('') +
  '"';

/** A C# constant expression of the text, one string literal a line. */
const constant = (text: string) => {
  const lines = text.split('\n');
  return lines.map((line, i) => `            ${literal(i < lines.length - 1 ? `${line}\n` : line)}`).join(' +\n');
};

writeFileSync(
  'tools/RepxDesigner/SqlScripts.cs',
  `// Generated by scripts/companion-scripts.ts from SCHEMA_SCRIPT and SAMPLE_OBJECT_SCRIPT in src/lib/sqlSchemaScript.ts. Do not edit.
namespace RepxDesigner
{
    internal static class SqlScripts
    {
        /// <summary>Forma's read-only layout script, the text a person runs in SSMS.</summary>
        public const string Schema =
${constant(SCHEMA_SCRIPT)};

        /// <summary>One table or view's sample rows, with @s, @n and @rows: binary and spatial columns left out, text and json cut.</summary>
        public const string Sample =
${constant(SAMPLE_OBJECT_SCRIPT)};
    }
}
`.replace(/\r\n/g, '\n'),
);
console.log(`SqlScripts.cs: the layout script, ${SCHEMA_SCRIPT.split('\n').length} lines; the sample, ${SAMPLE_OBJECT_SCRIPT.split('\n').length} lines`);
